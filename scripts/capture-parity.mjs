await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/modules/${demo.moduleId}`)
await shot('module-detail')
await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/views`)
await shot('views')
await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/views/${demo.viewId}`)
await shot('view-detail')
await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/pages`)
await shot('pages')
