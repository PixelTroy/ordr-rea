await shot('intake')
await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/cycles`)
await shot('cycles')
await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/cycles/${demo.cycleId}`)
