await shot('drafts')
await page.goto(`${base}/${demo.slug}/your-work`)
await shot('your-work')
await page.goto(`${base}/${demo.slug}/archives`)
await shot('archives')
await page.goto(`${base}/${demo.slug}/notifications`)
await shot('notifications')
