import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import { chromium } from '@playwright/test'
import { seedDemo } from './seed-demo.mjs'

const outDir = process.env.PARITY_DIR || '/opt/cursor/artifacts/parity'
const base = (process.env.SEED_BASE_URL || 'http://localhost:3000').replace(/\/$/, '')

const demo = await seedDemo()
await mkdir(outDir, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })

async function shot(name) {
  await page.waitForTimeout(400)
  await page.screenshot({ path: path.join(outDir, `${name}.png`) })
  console.log(name)
}

await page.goto(`${base}/login`)
await shot('login')
await page.goto(`${base}/signup`)
await shot('signup')
await page.goto(`${base}/login`)
await page.getByTestId('login-email').fill(demo.email)
await page.getByTestId('login-password').fill(demo.password)
await page.getByTestId('login-submit').click()
await page.waitForURL(new RegExp(`/${demo.slug}`))

await shot('home')
await page.getByTestId('workspace-switcher').click()
await shot('workspace-switcher')
await page.keyboard.press('Escape')

await page.getByRole('link', { name: 'Projects', exact: true }).click()
await shot('projects')
await page.getByTestId('project-card').filter({ hasText: 'Clone Research' }).click()
await page.waitForURL(/\/issues/)
await shot('issues-list')

const projectToggle = page.locator('aside button', { hasText: 'Clone Research' })
if (await projectToggle.count()) {
  await projectToggle.first().click()
  await shot('sidebar-project-nav')
}

await page.getByTestId('layout-kanban').click()
await shot('issues-kanban')
