await page.getByTestId('display-button').click()
await shot('issues-display')
await page.getByTestId('filter-button').click()
await shot('issues-filters')
await page.keyboard.press('Escape')

await page.getByTestId('add-work-item').click()
await shot('create-issue')
await page.getByRole('button', { name: 'Close' }).click()

await page.goto(`${base}/${demo.slug}/projects/${demo.projectId}/overview`)
await shot('overview')
