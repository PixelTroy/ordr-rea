import { expect, test } from '@playwright/test'

test('comment on a work item and open a collaborative page', async ({ page }) => {
  const stamp = Date.now()
  const slug = `lab-${stamp}`
  await page.goto('/signup')
  await page.getByTestId('signup-name').fill('Ada Lovelace')
  await page.getByTestId('signup-email').fill(`ada-${stamp}@example.com`)
  await page.getByTestId('signup-password').fill('password123')
  await page.getByTestId('signup-submit').click()
  await page.getByTestId('workspace-name').fill(`Lab ${stamp}`)
  await page.getByTestId('workspace-submit').click()
  await page.getByRole('link', { name: 'Projects', exact: true }).click()
  await page.getByTestId('add-project').click()
  await page.getByTestId('project-name').fill('Clone Research')
  await page.getByTestId('project-identifier').fill('CLONE')
  await page.getByTestId('project-submit').click()
  await page.getByTestId('add-work-item').click()
  await page.getByTestId('issue-title').fill('Survey competitors')
  await page.getByTestId('issue-submit').click()
  await page.getByTestId('issue-row').click()
  await page.getByRole('button', { name: 'Comments' }).click()
  const composer = page.getByTestId('comment-editor').locator('[contenteditable="true"]')
  await composer.click()
  await composer.pressSequentially('Please review the notes')
  await expect(composer).toContainText('Please review the notes')
  await page.getByTestId('comment-submit').click()
  await expect(page.getByTestId('comment')).toContainText('Please review the notes')

  await page.getByRole('link', { name: 'Work items' }).click()
  await page.getByTestId('tab-pages').click()
  await page.getByTestId('add-page').click()
  await expect(page.getByTestId('page-title')).toHaveValue('Untitled')
  await page.getByTestId('page-title').fill('Competitor Research Spec')
  await page.getByTestId('page-title').blur()
  const body = page.getByTestId('page-body').locator('[contenteditable="true"]')
  await expect(body).toBeVisible()
  await body.click()
  await body.pressSequentially('Shared spec')
  await expect(body).toContainText('Shared spec')
})
